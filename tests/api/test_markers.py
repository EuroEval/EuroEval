"""Public outcomes for persisted marker signatures and ownership rules."""

import json

import pytest

from euroeval_api.markers import (
    VolunteerMarker,
    parse_volunteer_marker,
    sign_volunteer_marker,
    verify_volunteer_marker,
    volunteer_assignees_match,
)

BASE: VolunteerMarker = {
    "protocol_version": "volunteer-worker/v1",
    "coordinator": "broker",
    "submission": "active",
    "leases": [],
}


def test_parser_rejects_duplicate_and_invalid_markers() -> None:
    """Reject ambiguous or malformed ownership while retaining a valid marker."""
    good = "<!--\teuroeval-volunteer-worker:v1 " + json.dumps(BASE) + " -->"
    assert parse_volunteer_marker(body=good) == BASE
    assert parse_volunteer_marker(body=good + "\n" + good) is None
    invalid = (
        "<!-- euroeval-volunteer-worker:v1 "
        + json.dumps({**BASE, "leases": [{}]})
        + " -->"
    )
    assert parse_volunteer_marker(body=invalid) is None


@pytest.mark.parametrize(
    "field", ["submissions", "completed_languages", "public_assignees"]
)
def test_parser_rejects_explicit_null_optional_collections(field: str) -> None:
    """Do not confuse invalid explicit nulls with absent historical fields.

    Args:
        field: Optional collection under validation.
    """
    body = (
        "<!-- euroeval-volunteer-worker:v1 "
        + json.dumps({**BASE, field: None})
        + " -->"
    )
    assert parse_volunteer_marker(body=body) is None


def test_persisted_typescript_signature_vector(monkeypatch: pytest.MonkeyPatch) -> None:
    """Accept the existing TypeScript signature but reject another issue or payload.

    Args:
        monkeypatch: Isolated fabricated marker secret.
    """
    monkeypatch.setenv("VOLUNTEER_MARKER_SECRET", "test-secret")
    signed = sign_volunteer_marker(issue_number=42, marker=BASE)
    # Generated by the existing protocol.ts signer with this exact marker/secret.
    assert signed["signature"] == "_LRSScsT6dEomQXUC32DQDMOWhYbCrHk47hINbz6PHY"
    assert verify_volunteer_marker(issue_number=42, marker=signed)
    assert not verify_volunteer_marker(issue_number=43, marker=signed)
    assert not verify_volunteer_marker(
        issue_number=42, marker={**signed, "coordinator": "someone-else"}
    )


def test_public_legacy_and_manual_assignee_rules() -> None:
    """Preserve manual public assignees and required legacy assignees."""
    marker: VolunteerMarker = {
        **BASE,
        "leases": [
            {
                "lease_id": "lease",
                "language": "da",
                "worker": "worker",
                "contributor": "owner",
                "expires_at": "2000-01-01T00:00:00Z",
                "ownership_mode": "public",
            }
        ],
    }
    assert volunteer_assignees_match(
        assignees=[{"login": "manual"}], marker=marker, now=0
    )
    assert not volunteer_assignees_match(
        assignees=[{"login": "manual"}], marker=BASE, now=0
    )
    del marker["leases"][0]["ownership_mode"]
    assert not volunteer_assignees_match(assignees=[], marker=marker, now=0)
    assert volunteer_assignees_match(
        assignees=[],
        marker=marker,
        now=1800000000000,
        include_expired_leases=True,
        allow_expired_unassigned=True,
    )
